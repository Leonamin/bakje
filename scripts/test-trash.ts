import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
process.env.ARCHIVE_DATA_DIR = fs.mkdtempSync(path.join(os.tmpdir(), "bakje-trash-test-"));
const { db, MEDIA_DIR } = await import("../src/lib/db");
const { manageItems, purgeExpired, cleanupTrashMedia } = await import("../src/lib/library-trash");
const d = db(), now = new Date().toISOString();
d.prepare("INSERT INTO library_storage(id,name,kind,root_path,status,created_at) VALUES(2,'test','linked','/tmp/trash-fixture','online',?)").run(now);
const id = Number(d.prepare("INSERT INTO library_item(storage_id,external_id,title,created_at,updated_at) VALUES(2,'fixture','fixture',?,?)").run(now,now).lastInsertRowid);
const change = Number(d.prepare("INSERT INTO library_change(kind,description,before_json,after_json,created_at) VALUES('test','test','[]','[]',?)").run(now).lastInsertRowid);
d.prepare("INSERT INTO library_change_item VALUES(?,?)").run(change,id);
const plan = Number(d.prepare("INSERT INTO library_organization(storage_id,token,target_dir,root_path,state,total,created_at,updated_at) VALUES(2,'token','target','/tmp/trash-fixture','ready',1,?,?)").run(now,now).lastInsertRowid);
d.prepare("INSERT INTO library_organization_item(plan_id,item_id,revision,previous_folder,previous_locked,destination_folder) VALUES(?,?,1,'',0,'target')").run(plan,id);
manageItems([id],"hide"); manageItems([id],"trash"); purgeExpired();
assert.ok(d.prepare("SELECT 1 FROM library_item WHERE id=?").get(id));
manageItems([id],"restore"); assert.ok((d.prepare("SELECT hidden_at FROM library_item WHERE id=?").get(id) as {hidden_at: string}).hidden_at);
manageItems([id],"trash"); d.prepare("UPDATE library_item SET deleted_at='2000-01-01T00:00:00.000Z' WHERE id=?").run(id); purgeExpired();
assert.equal(d.prepare("SELECT 1 FROM library_item WHERE id=?").get(id), undefined);
assert.ok(d.prepare("SELECT 1 FROM library_tombstone WHERE storage_id=2 AND external_id='fixture'").get());
assert.equal((d.prepare("SELECT state FROM library_organization WHERE id=?").get(plan) as {state:string}).state,"invalidated");
assert.ok((d.prepare("SELECT undone_at FROM library_change WHERE id=?").get(change) as {undone_at:string}).undone_at);
const file = path.join(MEDIA_DIR,"fixture.jpg"); fs.writeFileSync(file,"test"); fs.utimesSync(file, new Date(0),new Date(0));
d.prepare("INSERT INTO trash_media_cleanup VALUES('fixture.jpg')").run();
d.prepare("INSERT INTO source(platform,native_id,canonical_url,first_seen_at) VALUES('x','test','https://example.test',?)").run(now);
const sourceId = (d.prepare("SELECT id FROM source WHERE native_id='test'").get() as {id:number}).id;
d.prepare("INSERT INTO media(source_id,kind,remote_url,local_path,status) VALUES(?,'image','https://example.test/a','fixture.jpg','ok')").run(sourceId);
await cleanupTrashMedia(); assert.equal(fs.existsSync(file),true);
d.prepare("DELETE FROM source WHERE id=?").run(sourceId);
d.prepare("INSERT OR IGNORE INTO trash_media_cleanup VALUES('fixture.jpg')").run();
await cleanupTrashMedia(); assert.equal(fs.existsSync(file),false);
console.log("trash lifecycle, history invalidation and media cleanup passed");
