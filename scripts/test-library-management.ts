/** All moves and conflict fixtures live under an isolated temporary folder. Never uses operating data. */
import assert from "node:assert/strict";
import fs from "node:fs/promises";
import path from "node:path";
import os from "node:os";
import sharp from "sharp";
const temporary = await fs.mkdtemp(path.join(os.tmpdir(), "bakje-management-test-"));
const original = path.join(temporary, "originals");
await fs.mkdir(original);
await sharp({ create: { width: 20, height: 20, channels: 3, background: "#b7d894" } }).png().toFile(path.join(original, "result.png"));
await fs.writeFile(path.join(original, "result.mp4"), "video bytes");
process.env.ARCHIVE_DATA_DIR = path.join(temporary, "data");
process.env.EMBEDDER_URL = "";
process.env.BAKJE_ORGANIZATION_MANUAL = "1";
const { db } = await import("../src/lib/db");
const { connectStorage, resolveFile, fileHash } = await import("../src/lib/library-files");
const { registerItem, getLibraryItem, editLibraryItem } = await import("../src/lib/library-catalog");
const { updateComponents, splitItem, mergeItems, undoStructure, structureHistory } = await import("../src/lib/library-structure");
const { createOrganization, organizationPlan, organizationView, tickOrganizationWorker, controlOrganization } = await import("../src/lib/library-organization");
const { submitManifest, submitManifestFile, getRun, tickLibraryWorker } = await import("../src/lib/library-import");
const { MODEL_KEY } = await import("../src/lib/analysis-jobs");
const store = await connectStorage("원본 폴더", original);
const base = { external_id: "a", title: "정원 A", origin: "local", collections: ["정원"], components: [
  { key: "p", kind: "text", role: "prompt", language: "ko", text: "정원의 프롬프트" },
  { key: "i", kind: "image", role: "result", path: "result.png" },
  { key: "v", kind: "video", role: "result", path: "result.mp4" },
] };
const a = await registerItem(store.id, base, "명시적 묶음");
const b = await registerItem(store.id, { ...base, external_id: "b", title: "정원 B", components: base.components.slice(0, 2) }, "공유 파일");
const components = () => getLibraryItem(a.id)!.components;
const revision = (id = a.id) => getLibraryItem(id)!.item.revision;
const originalIds = components().map(c => c.id);
const vector = Buffer.from(new Float32Array([1, ...Array(255).fill(0)]).buffer);
for (const c of components().filter(c => c.kind !== "video")) db().prepare("INSERT INTO library_vector VALUES(?,?,?,?,?)").run(c.id, 0, c.input_hash, MODEL_KEY, vector);
const vectorCount = () => (db().prepare("SELECT COUNT(*) n FROM library_vector").get() as { n: number }).n;
const changed = updateComponents(a.id, revision(), [...components()].reverse().map(c => ({ id: c.id, role: c.kind === "image" ? "reference" : c.role, language: c.language })));
assert.deepEqual(components().map(c => c.id), [...originalIds].reverse());
assert.equal(components().find(c => c.kind === "image")!.role, "reference");
assert.equal(vectorCount(), 2);
assert.throws(() => updateComponents(a.id, 1, components().map(c => ({ id: c.id, role: c.role }))));
undoStructure(changed.change_id);
assert.deepEqual(components().map(c => c.id), originalIds);
const split = splitItem(a.id, revision(), [originalIds[1]], "분리한 이미지");
assert.equal(getLibraryItem(split.new_item_id)!.components[0].id, originalIds[1]); assert.equal(vectorCount(), 2);
assert.deepEqual(getLibraryItem(split.new_item_id)!.collections, ["정원"]);
undoStructure(split.change_id);
assert.deepEqual(components().map(c => c.id), originalIds);
assert.ok(getLibraryItem(split.new_item_id)!.item.hidden_at);
const merge = mergeItems(a.id, revision(), [{ id: b.id, revision: revision(b.id) }]);
assert.equal(components().length, 5);
assert.equal(new Set(components().map(c => c.component_key)).size, 5);
assert.ok(getLibraryItem(b.id)!.item.hidden_at); assert.equal(vectorCount(), 2);
undoStructure(merge.change_id);
assert.equal(getLibraryItem(b.id)!.components.length, 2); assert.equal(getLibraryItem(b.id)!.item.hidden_at, null);
const stale = updateComponents(a.id, revision(), components().map(c => ({ id: c.id, role: c.role, language: c.language })));
editLibraryItem(a.id, revision(), { note: "다른 수정" });
assert.throws(() => undoStructure(stale.change_id));
assert.ok(structureHistory(a.id).some(h => h.id === stale.change_id && !h.can_undo));
const otherRoot = path.join(temporary, "other"); await fs.mkdir(otherRoot);
const otherStore = await connectStorage("다른 저장소", otherRoot);
const other = await registerItem(otherStore.id, { external_id: "other", title: "다른 자료", components: [{ key: "p", kind: "text", role: "prompt", text: "other" }] }, "다른 저장소");
assert.throws(() => mergeItems(a.id, revision(), [{ id: other.id, revision: revision(other.id) }]));
await assert.rejects(createOrganization(store.id, [a.id], "../escape"));
const plan = await createOrganization(store.id, [a.id]);
await tickOrganizationWorker();
assert.equal(organizationPlan(plan.id).state, "ready", organizationPlan(plan.id).error ?? "");
await assert.rejects(fs.access(path.join(original, "bakje-organized")));
const preview = await organizationView(plan.id);
assert.equal(preview.affected_shared_items, 1);
await fs.chmod(original, 0o555);
assert.equal((await organizationView(plan.id)).writable, false);
await assert.rejects(controlOrganization(plan.id, "apply"));
await fs.chmod(original, 0o755);
// A destination created after preview is never overwritten, and preflight moves no other files.
const operation = db().prepare("SELECT * FROM library_organization_op WHERE plan_id=? AND kind='move' ORDER BY id LIMIT 1").get(plan.id) as { id: number; from_path: string; to_path: string; asset_id: number; sha256: string };
const destination = path.join(original, operation.to_path);
await fs.mkdir(path.dirname(destination), { recursive: true });
await fs.writeFile(destination, "foreign destination");
await controlOrganization(plan.id, "apply");
assert.throws(() => editLibraryItem(a.id, revision(), { note: "must wait" }));
const waiting = submitManifest(store.id, "정리 중 등록 대기", [base]);
await tickLibraryWorker();
assert.equal(getRun(waiting.id).state, "pending");
assert.equal(getRun(waiting.id).cursor, 0);
await tickOrganizationWorker();
assert.equal(organizationPlan(plan.id).state, "failed");
assert.equal(await fs.readFile(destination, "utf8"), "foreign destination");
await fs.access(path.join(original, operation.from_path));
await fs.unlink(destination);
await controlOrganization(plan.id, "retry");
await tickOrganizationWorker();
assert.equal(organizationPlan(plan.id).state, "applied", organizationPlan(plan.id).error ?? "");
await tickLibraryWorker();
for (let i = 0; i < 100 && getRun(waiting.id).state !== "done"; i++) await new Promise(r => setTimeout(r, 20));
assert.equal(getRun(waiting.id).state, "done", JSON.stringify(getRun(waiting.id)));
assert.equal(getRun(waiting.id).failed, 0);
assert.equal(vectorCount(), 2);
assert.deepEqual(components().map(c => c.id), originalIds);
assert.equal(getLibraryItem(b.id)!.components.find(c => c.kind === "image")!.asset_id, components().find(c => c.kind === "image")!.asset_id);
assert.equal((await registerItem(store.id, base, "이전 매니페스트")).state, "preserved");
const text = components().find(c => c.kind === "text")!; assert.ok(text.asset_id); assert.ok(text.relative_path);
await fs.access(await resolveFile(store.id, text.relative_path!));
const manifestFile = path.join(original, plan.target_dir, "items.jsonl");
const exported = JSON.parse((await fs.readFile(manifestFile, "utf8")).trim());
assert.equal(exported.path_base, "storage");
assert.equal(exported.external_id, "a");
for (const c of exported.components) await fs.access(await resolveFile(store.id, c.path));
// Reimport the generated manifest from a cloned root, without relying on the old catalog's locks.
const clone = path.join(temporary, "clone"); await fs.cp(original, clone, { recursive: true });
const cloneStore = await connectStorage("정리 결과 사본", clone);
const importRun = await submitManifestFile(cloneStore.id, `${plan.target_dir}/items.jsonl`, "정리 규격 재등록");
await tickLibraryWorker();
for (let i = 0; i < 100 && getRun(importRun.id).state !== "done"; i++) await new Promise(r => setTimeout(r, 20));
assert.equal(getRun(importRun.id).state, "done", JSON.stringify(getRun(importRun.id)));
// Undo refuses both external edits to outputs and occupied original paths.
const organizedBytes = await fs.readFile(destination);
await fs.writeFile(destination, "external edit");
await controlOrganization(plan.id, "undo"); await tickOrganizationWorker();
assert.equal(organizationPlan(plan.id).state, "failed");
assert.equal(await fs.readFile(destination, "utf8"), "external edit");
await fs.writeFile(destination, organizedBytes);
await fs.writeFile(path.join(original, operation.from_path), "new original");
await controlOrganization(plan.id, "retry"); await tickOrganizationWorker();
assert.equal(organizationPlan(plan.id).state, "failed");
assert.equal(await fs.readFile(path.join(original, operation.from_path), "utf8"), "new original");
await fs.unlink(path.join(original, operation.from_path));
await controlOrganization(plan.id, "retry"); await tickOrganizationWorker();
assert.equal(organizationPlan(plan.id).state, "undone", organizationPlan(plan.id).error ?? "");
assert.equal(await fileHash(path.join(original, operation.from_path)), operation.sha256);
assert.equal(components().find(c => c.kind === "text")!.asset_id, null);
assert.equal(components().find(c => c.kind === "image")!.relative_path, "result.png");
assert.equal(getLibraryItem(b.id)!.components.find(c => c.kind === "image")!.relative_path, "result.png");
assert.equal(vectorCount(), 2);
// Recover a crash between filesystem publication and the catalog checkpoint.
const interrupted = await createOrganization(store.id, [a.id], "recovery"); await tickOrganizationWorker();
assert.equal(organizationPlan(interrupted.id).state, "ready");
await controlOrganization(interrupted.id, "apply");
const op = db().prepare("SELECT * FROM library_organization_op WHERE plan_id=? AND kind='move' LIMIT 1").get(interrupted.id) as typeof operation;
await fs.mkdir(path.dirname(path.join(original, op.to_path)), { recursive: true });
await fs.writeFile(path.join(original, interrupted.target_dir, ".bakje-plan"), organizationPlan(interrupted.id).token);
await fs.link(path.join(original, op.from_path), path.join(original, op.to_path)); await fs.unlink(path.join(original, op.from_path));
db().prepare("UPDATE library_organization_op SET state='started' WHERE id=?").run(op.id);
db().prepare("UPDATE library_organization SET state='applying',claim_token='dead-worker',lease_until='2000-01-01T00:00:00.000Z' WHERE id=?").run(interrupted.id);
assert.equal(await resolveFile(store.id, op.from_path), path.join(original, op.to_path));
await tickOrganizationWorker();
assert.equal(organizationPlan(interrupted.id).state, "applied", organizationPlan(interrupted.id).error ?? "");
await controlOrganization(interrupted.id, "undo"); await tickOrganizationWorker();
assert.equal(organizationPlan(interrupted.id).state, "undone");
// Recover a cross-device copy interrupted before completion, in both directions.
const partial = await createOrganization(store.id, [a.id], "partial-copy"); await tickOrganizationWorker();
await controlOrganization(partial.id, "apply");
const partialOp = db().prepare("SELECT * FROM library_organization_op WHERE plan_id=? AND kind='move' LIMIT 1").get(partial.id) as typeof operation;
const partialFrom = path.join(original, partialOp.from_path), partialTo = path.join(original, partialOp.to_path);
const fullBytes = await fs.readFile(partialFrom);
await fs.mkdir(path.dirname(partialTo), { recursive: true });
await fs.writeFile(path.join(original, partial.target_dir, ".bakje-plan"), organizationPlan(partial.id).token);
await fs.writeFile(partialTo, fullBytes.subarray(0, Math.floor(fullBytes.length / 2)));
db().prepare("UPDATE library_organization_op SET state='started' WHERE id=?").run(partialOp.id);
await tickOrganizationWorker();
assert.equal(organizationPlan(partial.id).state, "applied", organizationPlan(partial.id).error ?? "");
assert.deepEqual(await fs.readFile(partialTo), fullBytes);
await controlOrganization(partial.id, "undo");
await fs.writeFile(partialFrom, fullBytes.subarray(0, Math.floor(fullBytes.length / 2)));
db().prepare("UPDATE library_organization_op SET state='undo_started' WHERE id=?").run(partialOp.id);
await tickOrganizationWorker();
assert.equal(organizationPlan(partial.id).state, "undone", organizationPlan(partial.id).error ?? "");
assert.deepEqual(await fs.readFile(partialFrom), fullBytes);
// A preview becomes stale after metadata edits, before any source file is moved.
const stalePlan = await createOrganization(store.id, [a.id], "stale-preview"); await tickOrganizationWorker();
editLibraryItem(a.id, revision(), { note: "계획 이후 변경" });
await assert.rejects(controlOrganization(stalePlan.id, "apply"));
await controlOrganization(stalePlan.id, "cancel");
// Destination symlinks cannot redirect writes outside the registered root.
await fs.symlink(otherRoot, path.join(original, "escape"));
const symlinkPlan = await createOrganization(store.id, [a.id], "escape"); await tickOrganizationWorker();
await controlOrganization(symlinkPlan.id, "apply"); await tickOrganizationWorker();
assert.equal(organizationPlan(symlinkPlan.id).state, "failed");
assert.deepEqual(await fs.readdir(otherRoot), []);
console.log("management integration: role/order, split/merge/undo, revision guards, embedding reuse, read-only gating, preview, no-clobber, shared files, manifest roundtrip, conflict-safe undo, crash recovery and symlink confinement passed");
console.log(`Temporary fixture: ${temporary}`);
process.exit(0);
